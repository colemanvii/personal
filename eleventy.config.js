import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { prune, report, ogUsed, CRISP_WIDTH } from "./lib/images.js";
import { renderMedia, picture, esc } from "./lib/media.js";

const SHOW_DRAFTS = process.env.DRAFTS === "1";
const OUTPUT = "site";
// Everything Eleventy writes is regenerated each build, except encoded images,
// which are kept (by content hash) so unchanged sources are never re-encoded.
const KEEP = new Set(["img", "og"]);

export default function (eleventyConfig) {
  eleventyConfig.setQuietMode(true);
  eleventyConfig.addGlobalData("showDrafts", SHOW_DRAFTS);

  // Only the template formats are templates; image files beside them are inputs to the pipeline.
  eleventyConfig.setTemplateFormats(["njk", "md"]);
  eleventyConfig.addPassthroughCopy({ "src/assets/fonts": "fonts" });
  eleventyConfig.addPassthroughCopy({ "src/assets/js": "js" });
  eleventyConfig.addPassthroughCopy({ "src/assets/share.jpg": "share.jpg" });
  for (const f of ["favicon.svg", "_redirects", "_headers", "_routes.json", "robots.txt"]) {
    eleventyConfig.addPassthroughCopy(`src/${f}`);
  }

  eleventyConfig.on("eleventy.before", () => {
    if (!fs.existsSync(OUTPUT)) return;
    for (const name of fs.readdirSync(OUTPUT)) {
      if (!KEEP.has(name)) fs.rmSync(path.join(OUTPUT, name), { recursive: true, force: true });
    }
  });

  eleventyConfig.on("eleventy.after", async () => {
    prune();
    if (fs.existsSync(`${OUTPUT}/og`)) {
      for (const n of fs.readdirSync(`${OUTPUT}/og`)) if (!ogUsed.has(n)) fs.rmSync(`${OUTPUT}/og/${n}`);
    }
    // Home-screen and app icons from the SVG favicon.
    for (const [name, size] of [["apple-touch-icon.png", 180], ["icon-192.png", 192], ["icon-512.png", 512]]) {
      await sharp("src/favicon.svg", { density: 600 }).resize(size, size).png().toFile(`${OUTPUT}/${name}`);
    }
    // favicon.ico for Safari, Windows and anything that asks for it at the root.
    const pngs = [];
    for (const size of [16, 32, 48]) pngs.push([size, await sharp("src/favicon.svg", { density: 600 }).resize(size, size).png().toBuffer()]);
    fs.writeFileSync(`${OUTPUT}/favicon.ico`, ico(pngs));
    writeReport();
  });

  // ---------- works ----------
  eleventyConfig.addCollection("works", api =>
    api.getFilteredByGlob("src/work/*/index.md")
      .filter(p => SHOW_DRAFTS || !p.data.draft)
      .sort((a, b) => (a.data.order ?? 999) - (b.data.order ?? 999) || a.data.title.localeCompare(b.data.title))
  );

  eleventyConfig.addFilter("disciplines", (works, all) =>
    all.filter(d => works.some(w => (w.data.disciplines || []).includes(d))));
  eleventyConfig.addFilter("pad", n => String(n).padStart(3, "0"));
  eleventyConfig.addFilter("lower", s => String(s).toLowerCase());
  eleventyConfig.addFilter("hasPage", w => Boolean(w.data.media?.length));

  // {% media %} renders the current work's media list.
  eleventyConfig.addAsyncShortcode("media", async function (media) {
    const ctx = { dir: path.dirname(this.page.inputPath), slug: this.page.fileSlug, first: { done: false } };
    const out = [];
    // Each item is one screen: on a large screen it is centred in a viewport of its own.
    for (const m of media || []) out.push(`<div class="screen">${await renderMedia(ctx, m)}</div>`);
    return out.join("\n");
  });

  // {% picture "file.jpg", "alt", "sizes", eager %} for images that belong to a page, not a work.
  eleventyConfig.addAsyncShortcode("picture", async function (src, alt, sizes, eager = false) {
    const ctx = { dir: path.dirname(this.page.inputPath), slug: this.page.fileSlug || "home", first: { done: !eager } };
    return picture(ctx, src, alt, sizes);
  });

  eleventyConfig.addFilter("inlineCss", file => fs.readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s*\n\s*/g, "\n"));
  eleventyConfig.addFilter("esc", esc);
  eleventyConfig.addFilter("year", () => new Date().getFullYear());

  return {
    dir: { input: "src", output: OUTPUT, includes: "_includes", data: "_data" },
    markdownTemplateEngine: false,
    htmlTemplateEngine: "njk",
  };
}

// An .ico holding PNG images: a 6-byte header, a 16-byte entry per image, then the images.
function ico(pngs) {
  const head = Buffer.alloc(6 + 16 * pngs.length);
  head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(pngs.length, 4);
  let offset = head.length;
  pngs.forEach(([size, png], i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size % 256, e); head.writeUInt8(size % 256, e + 1);
    head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(png.length, e + 8); head.writeUInt32LE(offset, e + 12);
    offset += png.length;
  });
  return Buffer.concat([head, ...pngs.map(([, png]) => png)]);
}

function writeReport() {
  const lines = [
    "# Media report",
    "",
    "Generated by `npm run build`. Do not edit by hand.",
    "",
    `Images narrower than ${CRISP_WIDTH}px can look soft at full width on a 3× phone screen. Logos should be SVG. Every image needs alt text.`,
    "",
  ];
  if (!report.length) lines.push("Nothing to fix.");
  else {
    lines.push("| Work | File | Issue |", "| --- | --- | --- |");
    for (const r of [...report].sort((a, b) => a.work.localeCompare(b.work) || a.file.localeCompare(b.file))) {
      lines.push(`| ${r.work} | ${r.file} | ${r.issue} |`);
    }
  }
  fs.writeFileSync("MEDIA-REPORT.md", lines.join("\n") + "\n");
  if (report.length) console.log(`[media] ${report.length} item(s) to fix: see MEDIA-REPORT.md`);
}
